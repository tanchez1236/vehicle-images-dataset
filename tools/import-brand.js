const fs = require('fs');
const path = require('path');
const readline = require('readline');

const ROOT = path.join(__dirname, '..');

const catalogDir = path.join(ROOT, 'catalog');
const imagesDir = path.join(ROOT, 'images');

const stats = {
  modelsProcessed: 0,
  modelsNew: 0,

  generationsProcessed: 0,
  generationsNew: 0,

  colorsProcessed: 0,
  colorsNew: 0,

  foldersCreated: 0
};

function logSection(title) {
  console.log('');
  console.log('='.repeat(60));
  console.log(title);
  console.log('='.repeat(60));
}

function logInfo(message) {
  console.log(`ℹ️  ${message}`);
}

function logNew(message) {
  console.log(`✅ ${message}`);
}

function logExisting(message) {
  console.log(`↺ ${message}`);
}

function colorFolderName(colorName, colorCode) {
  return `${colorName} [${colorCode}]`
    .replace(/[<>:"/\\|?*]/g, '')
    .trim();
}

function ensureDir(dir) {
  fs.mkdirSync(dir, { recursive: true });
}

function slug(text) {
  return String(text || '')
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');
}

function loadJson(file) {
  if (!fs.existsSync(file)) return null;
  return JSON.parse(fs.readFileSync(file, 'utf8'));
}

function saveJson(file, data) {
  fs.writeFileSync(file, JSON.stringify(data, null, 2));
}

function findOrCreateModel(catalog, modelName) {
    stats.modelsProcessed++;
  let model = catalog.models.find(
    m => m.name.toLowerCase() === modelName.toLowerCase()
  );

  if (!model) {
    model = {
      name: modelName,
      generations: []
    };

    catalog.models.push(model);

    stats.modelsNew++;

    logNew(`Modelo nuevo: ${modelName}`);
  } else {
    logExisting(`Modelo existente: ${modelName}`);
  }

  return model;
}

function findOrCreateGeneration(
  model,
  generationName,
  fromYear,
  toYear
) {
  let generation = model.generations.find(
    g => g.name.toLowerCase() === generationName.toLowerCase()
  );

  if (!generation) {
    generation = {
      name: generationName,
      years: {
        from: Number(fromYear),
        to: Number(toYear)
      },
      colors: []
    };

    model.generations.push(generation);

    stats.generationsNew++;

    logNew(
      `Generación nueva: ${model.name} > ${generationName}`
    );
  } else {
    logExisting(
      `Generación existente: ${model.name} > ${generationName}`
    );
  }

  return generation;
}

function ensureColor(
  catalog,
  colorCode,
  colorSlug,
  colorName,
  hex
) {
    stats.colorsProcessed++;
  if (!catalog.colors[colorCode]) {
    catalog.colors[colorCode] = {
      slug: colorSlug,
      name: colorName,
      hex
    };

    stats.colorsNew++;

    logNew(
      `Color nuevo: ${colorName} (${colorCode})`
    );
  } else {
    logExisting(
      `Color existente: ${colorName} (${colorCode})`
    );
  }
}

function ensureGenerationColor(
  generation,
  colorCode,
  fromYear,
  toYear
) {
  const exists = generation.colors.find(
    c => c.code === colorCode
  );

  if (exists) return;

  generation.colors.push({
    code: colorCode,
    from: Number(fromYear),
    to: Number(toYear)
  });
}

function createImageFolders(catalog) {
  const makeSlug = slug(catalog.make);

  for (const model of catalog.models) {
    const modelSlug = slug(model.name);

    for (const generation of model.generations) {
      const generationSlug = slug(generation.name);

      for (const color of generation.colors) {

        const colorData =
          catalog.colors[color.code];

        if (!colorData) continue;

        const folderPath = path.join(
          imagesDir,
          makeSlug,
          modelSlug,
          generationSlug,
          colorFolderName(
            colorData.name,
            color.code
          )
        );

        const existed =
          fs.existsSync(folderPath);

        ensureDir(folderPath);

        const placeholder =
          path.join(folderPath, '.placeholder');

        if (!fs.existsSync(placeholder)) {
          fs.writeFileSync(
            placeholder,
            'Generated by dataset importer'
          );
        }

        if (!existed) {
          stats.foldersCreated++;

          console.log(
            `📁 ${folderPath}`
          );
        }
      }
    }
  }
}

function generateIndex() {
  const files = fs.readdirSync(catalogDir);

  const makes = files
    .filter(file => file.endsWith('.json'))
    .filter(file => file !== 'index.json')
    .map(file => path.basename(file, '.json'))
    .sort();

  const index = {
    schemaVersion: 1,
    updatedAt: new Date().toISOString(),
    totalMakes: makes.length,
    makes
};

  const indexFile = path.join(
    catalogDir,
    'index.json'
  );

  fs.writeFileSync(
    indexFile,
    JSON.stringify(index, null, 2)
  );

  return index;
}

async function askBrand() {

  const importsDir =
    path.join(ROOT, 'imports');

  const txtFiles =
    fs.readdirSync(importsDir)
      .filter(f => f.endsWith('.txt'))
      .sort();

  if (txtFiles.length === 0) {

    console.log('');
    console.log(
      '❌ No se encontraron archivos TXT en imports/'
    );

    process.exit(1);
  }

  console.log('');
  console.log('TXT disponibles:\n');

  txtFiles.forEach((file, index) => {

    console.log(
      `[${index + 1}] ${path.basename(file, '.txt')}`
    );

  });

  console.log('');

  const rl = readline.createInterface({
    input: process.stdin,
    output: process.stdout
  });

  return new Promise(resolve => {

    rl.question(
      'Marca a importar: ',
      answer => {

        rl.close();

        const value =
          answer.trim();

        const numeric =
          parseInt(value, 10);

        if (
          !isNaN(numeric) &&
          numeric >= 1 &&
          numeric <= txtFiles.length
        ) {

          resolve(
            path.basename(
              txtFiles[numeric - 1],
              '.txt'
            )
          );

          return;
        }

        resolve(
          value.toLowerCase()
        );

      }
    );

  });

}

(async () => {
  ensureDir(catalogDir);
  ensureDir(imagesDir);

  const brand =  await askBrand();

  const filePath = path.join(ROOT, 'imports', `${brand}.txt`);

  if (!fs.existsSync(filePath)) {
    console.log('');
    console.log(
    `❌ No existe imports/${brand}.txt`
    );

    process.exit(1);
    console.error('❌ Archivo no encontrado');
    process.exit(1);
  }

  const lines = fs
    .readFileSync(filePath, 'utf8')
    .split(/\r?\n/)
    .map(x => x.trim())
    .filter(Boolean);

  let make = '';
  let currentModel = null;
  let currentGeneration = null;

  for (const line of lines) {
    const parts = line.split('|');

    if (parts[0] === 'MAKE') {
      make = parts[1];
      break;
    }
  }

  if (!make) {
    logSection('IMPORTADOR DATASET V2');

    logInfo(`Archivo: ${filePath}`);
    logInfo(`Marca: ${make}`);

    console.error('❌ No se encontró MAKE');
    process.exit(1);
  }

  const catalogFile =
    path.join(catalogDir, `${slug(make)}.json`);

  const catalog =
    loadJson(catalogFile) || {
      make,
      colors: {},
      models: []
    };

  for (const line of lines) {
    const parts = line.split('|');

    const type = parts[0];

    if (type === 'MODEL') {
      currentModel = findOrCreateModel(
        catalog,
        parts[1]
      );
    }

    else if (type === 'GENERATION') {
      currentGeneration =
        findOrCreateGeneration(
          currentModel,
          parts[1],
          parts[2],
          parts[3]
        );
    }

    else if (type === 'COLOR') {
      const [
        ,
        colorSlug,
        colorName,
        colorCode,
        hex,
        fromYear,
        toYear
      ] = parts;

      ensureColor(
        catalog,
        colorCode,
        colorSlug,
        colorName,
        hex
      );

      ensureGenerationColor(
        currentGeneration,
        colorCode,
        fromYear,
        toYear
      );
    }
  }

  saveJson(catalogFile, catalog);

  createImageFolders(catalog);

  const index = generateIndex();

  logSection('RESUMEN');

console.log(`🏭 Marca: ${make}`);
console.log(`📄 JSON: ${catalogFile}`);

console.log('');
console.log(`Modelos procesados:      ${stats.modelsProcessed}`);
console.log(`Modelos nuevos:          ${stats.modelsNew}`);

console.log('');

console.log(`Generaciones procesadas: ${stats.generationsProcessed}`);
console.log(`Generaciones nuevas:     ${stats.generationsNew}`);

console.log('');

console.log(`Colores procesados:      ${stats.colorsProcessed}`);
console.log(`Colores nuevos:          ${stats.colorsNew}`);

console.log('');

console.log(`Carpetas creadas:        ${stats.foldersCreated}`);

console.log('');
console.log('✅ Importación finalizada');

console.log('');
console.log(`📚 Marcas catalogadas: ${index.totalMakes}`);
})();